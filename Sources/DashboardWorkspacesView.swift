    // MARK: - Row Helpers
    private func presetConnectorRow(preset: AssistantConnector) -> some View {
        let isDetected = connectorManager.isPathDetected(path: preset.path)
        let iconName: String
        let iconColor: Color
        
        switch preset.id {
        case "preset_cursor":
            iconName = "cursorarrow.rays"
            iconColor = .indigo
        case "preset_cline":
            iconName = "chevron.left.slash.chevron.right"
            iconColor = .blue
        case "preset_roocode":
            iconName = "kangaroo.fill"
            iconColor = .teal
        case "preset_windsurf":
            iconName = "wind"
            iconColor = .cyan
        case "preset_hermes":
            iconName = "flame.fill"
            iconColor = .orange
        case "preset_aider":
            iconName = "pencil.and.outline"
            iconColor = .pink
        default:
            iconName = "person.crop.circle"
            iconColor = .gray
        }
        
        return HStack(spacing: 12) {
            ZStack {
                RoundedRectangle(cornerRadius: 6, style: .continuous)
                    .fill(iconColor.opacity(0.15))
                    .frame(width: 28, height: 28)
                Image(systemName: iconName)
                    .font(.system(size: 13, weight: .semibold))
                    .foregroundColor(iconColor)
            }
            
            VStack(alignment: .leading, spacing: 2) {
                HStack(spacing: 6) {
                    Text(preset.name)
                        .font(.system(size: 13, weight: .medium))
                        .foregroundColor(.primary)
                    
                    HStack(spacing: 3) {
                        Circle()
                            .fill(isDetected ? Color.green : Color.secondary.opacity(0.4))
                            .frame(width: 6, height: 6)
                        Text(isDetected ? "Detected" : "Not Installed")
                            .font(.system(size: 10))
                            .foregroundColor(isDetected ? .green : .secondary)
                    }
                }
                Text(preset.path)
                    .font(.system(size: 10, design: .monospaced))
                    .foregroundColor(.secondary)
                    .lineLimit(1)
                    .truncationMode(.middle)
            }
            Spacer()
            
            Toggle("", isOn: Binding(
                get: { preset.isEnabled },
                set: { connectorManager.toggleConnector(id: preset.id, enabled: $0) }
            ))
            .toggleStyle(.switch)
        }
        .padding(.horizontal, 14)
        .padding(.vertical, 10)
    }
    
