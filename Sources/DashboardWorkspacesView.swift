    private func cliCodeSnippet(label: String, code: String) -> some View {
        VStack(alignment: .leading, spacing: 4) {
            Text(label)
                .font(.system(size: 10, weight: .semibold))
                .foregroundColor(.secondary)
            HStack {
                Text(code)
                    .font(.system(size: 11, design: .monospaced))
                    .foregroundColor(.primary)
                    .lineLimit(1)
                Spacer()
                Button(action: {
                    let pasteboard = NSPasteboard.general
                    pasteboard.clearContents()
                    pasteboard.setString(code, forType: .string)
                }) {
                    Image(systemName: "doc.on.doc")
                        .font(.system(size: 10))
                        .foregroundColor(.secondary)
                }
                .buttonStyle(.plain)
            }
            .padding(8)
            .background(Color(nsColor: .textBackgroundColor).opacity(0.7))
            .clipShape(RoundedRectangle(cornerRadius: 6, style: .continuous))
        }
    }
    
    // MARK: - Actions
    private func copyPromptToClipboard() {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.setString(UniversalConnectorManager.universalPromptText, forType: .string)
        promptCopied = true
        DispatchQueue.main.asyncAfter(deadline: .now() + 2.5) {
            self.promptCopied = false
        }
    }
    
    private func applyRecipeJSON() {
        let result = UniversalConnectorManager.shared.parseAndAddRecipe(from: recipeInput)
        switch result {
        case .success(let connector):
            recipeFeedbackMessage = "Successfully connected '\(connector.name)'!"
            recipeFeedbackIsError = false
            recipeInput = ""
            DispatchQueue.main.asyncAfter(deadline: .now() + 4.0) {
                if !self.recipeFeedbackIsError {
                    self.recipeFeedbackMessage = nil
                }
            }
        case .failure(let err):
            recipeFeedbackMessage = err.localizedDescription
            recipeFeedbackIsError = true
        }
    }
    
    private func selectPathWithPanel() {
        let panel = NSOpenPanel()
        panel.canChooseFiles = true
        panel.canChooseDirectories = true
        panel.allowsMultipleSelection = false
        panel.resolvesAliases = true
        
        if panel.runModal() == .OK, let url = panel.url {
            manualPath = url.path
        }
    }
    
    private func addManualWatcher() {
        let validation = SecurityPathValidator.validate(path: manualPath)
        guard validation.isValid else {
            manualFeedbackMessage = validation.errorMessage ?? "Invalid path"
            manualFeedbackIsError = true
            return
        }
        
        let connector = AssistantConnector(
            name: manualName,
            path: validation.sanitizedPath,
            format: manualFormat,
            isPreset: false,
            isEnabled: true
        )
        
        connectorManager.customConnectors.append(connector)
        connectorManager.saveConnectors()
        
        manualFeedbackMessage = "Added '\(manualName)' successfully!"
        manualFeedbackIsError = false
        manualName = ""
        manualPath = ""
        
        DispatchQueue.main.asyncAfter(deadline: .now() + 4.0) {
            if !self.manualFeedbackIsError {
                self.manualFeedbackMessage = nil
            }
        }
    }
    
    private func checkPath(_ rawPath: String) -> Bool {
        let validation = SecurityPathValidator.validate(path: rawPath)
        guard validation.isValid else { return false }
        return FileManager.default.fileExists(atPath: validation.sanitizedPath)
    }
